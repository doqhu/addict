/// The sections of the credits, in `CREDITS` and in the application: their
/// headings and their rows, the indexes first.
pub const SECTIONS: [(&str, &[Row]); 2] = [("Dictionary indexes", ROWS), ("OCR", OCR)];

/// The command that writes `CREDITS` anew from the tables.
pub const WRITE_CREDITS: &str = "ADDICT_WRITE_CREDITS=1 cargo test -p addict-dictionary credits";

/// The text of `CREDITS`: a header naming addict and its license, then a
/// block per row, the indexes in table order and then, under its own
/// heading, OCR. Each block is the index, its credit line, its license and
/// its upstream file.
pub fn credits() -> String {
    let mut text = String::new();
    text.push_str("Credits of addict\n");
    text.push_str("=================\n\n");
    text.push_str("addict is licensed under the MIT License (see LICENSES/MIT.txt).\n");
    text.push_str("It uses the dictionary data and the OCR data and software below,\n");
    text.push_str("each under its own license.\n\n");
    text.push_str("This file is generated from crates/addict-dictionary/src/sources.rs;\n");
    text.push_str(&format!(
        "do not edit it, regenerate it with `{WRITE_CREDITS}`.\n"
    ));
    for (heading, rows) in SECTIONS {
        text.push_str(&format!("\n\n{heading}\n{}\n", "-".repeat(heading.len())));
        for row in rows {
            text.push_str(&format!(
                "\n{}\n  Credit:   {}\n  License:  {}\n  Upstream: {}\n",
                row.index, row.credit, row.license, row.upstream
            ));
        }
    }
    text
}

/// The row of `source`. No wildcard arm: a new source does not compile until
/// it is given a row.
pub fn row(source: Source) -> &'static Row {
    match source {
        Source::Oewn => &OEWN,
        Source::Freedict => &FREEDICT,
        Source::KaikkiEs => &KAIKKI_ES,
        Source::WikdictEsRu => &WIKDICT_ES_RU,
        Source::OmwEs => &OMW_ES,
        Source::KaikkiEnSpanish => &KAIKKI_EN_SPANISH,
        Source::WikdictCaRu => &WIKDICT_CA_RU,
        Source::DbnaryCa => &DBNARY_CA,
        Source::SinonimsCat => &SINONIMS_CAT,
        Source::KaikkiEnCatalan => &KAIKKI_EN_CATALAN,
        Source::WikdictRuEn => &WIKDICT_RU_EN,
        Source::WikdictRuEs => &WIKDICT_RU_ES,
        Source::WikdictRuCa => &WIKDICT_RU_CA,
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;
    use crate::import::KNOWN;

    /// The indexes named in the notes on the dictionary sources, typed in
    /// here because those notes are not in the repository.
    const DOCUMENTED: &[&str] = &[
        "kaikki-es-Espanol",
        "kaikki-en-Spanish",
        "kaikki-en-Catalan",
        "wikdict-es-ru",
        "wikdict-ca-ru",
        "wikdict-ru-en",
        "wikdict-ru-es",
        "wikdict-ru-ca",
        "dbnary-ca",
        "freedict",
        "oewn",
        "omw-es",
        "sinonims-cat",
    ];

    /// Every source, listed here rather than taken from `KNOWN`, which lists
    /// file editions and may hold several per source.
    const ALL: &[Source] = &[
        Source::Oewn,
        Source::Freedict,
        Source::KaikkiEs,
        Source::WikdictEsRu,
        Source::OmwEs,
        Source::KaikkiEnSpanish,
        Source::WikdictCaRu,
        Source::DbnaryCa,
        Source::SinonimsCat,
        Source::KaikkiEnCatalan,
        Source::WikdictRuEn,
        Source::WikdictRuEs,
        Source::WikdictRuCa,
    ];

    /// The table has a row for every documented index and none other.
    #[test]
    fn sources_cover_every_documented_index() {
        let documented: BTreeSet<&str> = DOCUMENTED.iter().copied().collect();
        let rows: BTreeSet<&str> = ROWS.iter().map(|row| row.index).collect();
        assert_eq!(rows, documented);
    }

    /// Every row, of the indexes and of OCR, has a license and a credit.
    #[test]
    fn sources_have_a_license_and_a_credit() {
        for row in ROWS.iter().chain(OCR) {
            assert!(!row.license.trim().is_empty(), "{}: no license", row.index);
            assert!(!row.credit.trim().is_empty(), "{}: no credit", row.index);
        }
    }

    /// Every index row names its authors and gives the license URI and the
    /// link as `https://` addresses, the URI of the license its text names;
    /// the OCR rows, which no index carries, give none of them.
    #[test]
    fn sources_have_an_author_a_license_uri_and_a_link() {
        for row in ROWS {
            assert!(!row.author.trim().is_empty(), "{}: no author", row.index);
            for uri in [row.license_uri, row.link] {
                assert!(uri.starts_with("https://"), "{}: {uri:?}", row.index);
            }
            let share_alike = row.license.contains("BY-SA");
            assert_eq!(
                row.license_uri.contains("/by-sa/"),
                share_alike,
                "{}: {} vs {}",
                row.index,
                row.license,
                row.license_uri
            );
            if !share_alike {
                assert!(row.license_uri.contains("/by/"), "{}", row.index);
            }
            for version in ["3.0", "4.0"] {
                if row.license.contains(version) {
                    assert!(
                        row.license_uri.ends_with(&format!("/{version}/")),
                        "{}: {} vs {}",
                        row.index,
                        row.license,
                        row.license_uri
                    );
                }
            }
        }
        for row in OCR {
            assert_eq!(
                (row.author, row.license_uri, row.link),
                ("", "", ""),
                "{}",
                row.index
            );
        }
        for text in [MODIFIED, DISCLAIMER] {
            assert!(!text.trim().is_empty());
        }
    }

    /// The row of a source names its index file, and the rows follow the
    /// order in which the sources first appear in `KNOWN`.
    #[test]
    fn sources_match_the_index_files_in_known_order() {
        for &source in ALL {
            assert_eq!(
                format!("{}.index", row(source).index),
                source.index_name(),
                "{source:?}"
            );
        }
        let mut order: Vec<Source> = Vec::new();
        for file in KNOWN {
            if !order.contains(&file.source) {
                order.push(file.source);
            }
        }
        let expected: Vec<&str> = order.iter().map(|&source| row(source).index).collect();
        let actual: Vec<&str> = ROWS.iter().map(|row| row.index).collect();
        assert_eq!(actual, expected);
    }

    /// The committed `CREDITS` is the text of the tables. With
    /// `ADDICT_WRITE_CREDITS=1` the test writes the file instead.
    #[test]
    fn credits_file_is_up_to_date() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../CREDITS");
        let expected = credits();
        if std::env::var_os("ADDICT_WRITE_CREDITS").is_some_and(|value| value == "1") {
            std::fs::write(path, &expected).expect("writing CREDITS");
            return;
        }
        let committed = std::fs::read_to_string(path).unwrap_or_default();
        assert!(
            committed == expected,
            "CREDITS differs from the tables in sources.rs: run `{WRITE_CREDITS}`"
        );
    }

    /// Every row, of the indexes and then of OCR, is in the credits once
    /// with its credit line, in table order.
    #[test]
    fn credits_list_every_row_once_in_order() {
        let text = credits();
        let mut from = 0;
        for row in ROWS.iter().chain(OCR) {
            let block = format!("\n{}\n  Credit:   {}\n", row.index, row.credit);
            assert_eq!(text.matches(&block).count(), 1, "{}", row.index);
            let at = text[from..].find(&block).expect("in table order") + from;
            from = at + block.len();
        }
        let ocr = text.find("\nOCR\n").expect("the OCR heading");
        let first_ocr = text
            .find(&format!("\n{}\n", OCR[0].index))
            .expect("OCR row");
        let last_index = text
            .find(&format!("\n{}\n", ROWS[ROWS.len() - 1].index))
            .expect("index row");
        assert!(last_index < ocr && ocr < first_ocr);
    }

    /// The sections hold every row once, the indexes and then OCR, in
    /// table order.
    #[test]
    fn sections_list_every_row_once_in_table_order() {
        let listed: Vec<&str> = SECTIONS
            .iter()
            .flat_map(|(_, rows)| rows.iter().map(|row| row.index))
            .collect();
        let table: Vec<&str> = ROWS.iter().chain(OCR).map(|row| row.index).collect();
        assert_eq!(listed, table);
        assert_eq!(listed.len(), 15);
    }

    /// Only OEWN is downloaded by the builder, from the published file the
    /// importer knows; OCR is never downloaded.
    #[test]
    fn only_oewn_has_a_download_url_of_its_known_file() {
        let with_url: Vec<&str> = ROWS
            .iter()
            .filter(|row| row.url.is_some())
            .map(|row| row.index)
            .collect();
        assert_eq!(with_url, ["oewn"]);
        assert!(OCR.iter().all(|row| row.url.is_none()));
        let url = row(Source::Oewn).url.expect("a url");
        assert!(url.starts_with("https://"), "{url}");
        let known = KNOWN
            .iter()
            .find(|file| file.source == Source::Oewn)
            .expect("known");
        assert!(url.ends_with(&format!("/{}", known.name)), "{url}");
    }

    /// No index has two rows.
    #[test]
    fn sources_have_no_duplicate_index() {
        let mut seen = BTreeSet::new();
        for row in ROWS {
            assert!(seen.insert(row.index), "{}: two rows", row.index);
        }
    }
}
